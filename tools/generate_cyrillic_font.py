from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
FONT_PATH = Path(r"C:\Windows\Fonts\arial.ttf")
OUTPUT_PATH = ROOT / "Core" / "Src" / "ui_font_cyrillic_14.c"
FONT_SIZE = 14

ASCII_CODEPOINTS = list(range(0x20, 0x7F))
CYRILLIC_CODEPOINTS = [0x401, *range(0x410, 0x450), 0x451]
CODEPOINTS = ASCII_CODEPOINTS + CYRILLIC_CODEPOINTS


def format_bytes(values: list[int], indent: str = "    ") -> str:
    lines = []
    for start in range(0, len(values), 16):
        chunk = values[start : start + 16]
        lines.append(indent + ", ".join(f"0x{value:02x}" for value in chunk) + ",")
    return "\n".join(lines)


font = ImageFont.truetype(str(FONT_PATH), FONT_SIZE)
ascent, descent = font.getmetrics()
bitmap: list[int] = []
descriptors: list[tuple[int, int, int, int, int, int]] = []

for codepoint in CODEPOINTS:
    character = chr(codepoint)
    left, top, right, bottom = font.getbbox(character, anchor="ls")
    width = max(0, right - left)
    height = max(0, bottom - top)
    bitmap_index = len(bitmap)

    if width and height:
        image = Image.new("L", (width, height), 0)
        draw = ImageDraw.Draw(image)
        draw.text((-left, -top), character, font=font, fill=255, anchor="ls")
        pixels = list(image.get_flattened_data())
        for pixel_index in range(0, len(pixels), 2):
            high = min(15, (pixels[pixel_index] + 8) // 17)
            low = 0
            if pixel_index + 1 < len(pixels):
                low = min(15, (pixels[pixel_index + 1] + 8) // 17)
            bitmap.append((high << 4) | low)

    advance = int(round(font.getlength(character) * 16.0))
    descriptors.append((bitmap_index, advance, width, height, left, -bottom))

cyrillic_offsets = [codepoint - 0x401 for codepoint in CYRILLIC_CODEPOINTS]

descriptor_lines = [
    "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},"
]
for values in descriptors:
    descriptor_lines.append(
        "    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},"
        % values
    )

source = f'''/* Generated by tools/generate_cyrillic_font.py from Windows Arial. */
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
{format_bytes(bitmap)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(descriptor_lines)}
}};

static const uint16_t cyrillic_unicode_list[] = {{
{format_bytes(cyrillic_offsets)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{
        .range_start = 0x20, .range_length = 0x5f, .glyph_id_start = 1,
        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
        .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY
    }},
    {{
        .range_start = 0x401, .range_length = 0x51, .glyph_id_start = 96,
        .unicode_list = cyrillic_unicode_list, .glyph_id_ofs_list = NULL,
        .list_length = {len(CYRILLIC_CODEPOINTS)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
    }}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 2,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0
}};

const lv_font_t ui_font_cyrillic_14 = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
#if LV_VERSION_CHECK(9, 6, 0) || LVGL_VERSION_MAJOR >= 10
    .cap_height = {ascent},
    .x_height = {ascent // 2},
#endif
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2,
    .underline_thickness = 1,
#if LV_VERSION_CHECK(9, 3, 0)
    .static_bitmap = 1,
#endif
    .dsc = &font_dsc,
    .fallback = &lv_font_montserrat_14,
    .user_data = NULL,
}};
'''

OUTPUT_PATH.write_text(source, encoding="utf-8", newline="\n")
print(f"Generated {OUTPUT_PATH} ({len(CODEPOINTS)} glyphs, {len(bitmap)} bitmap bytes)")
